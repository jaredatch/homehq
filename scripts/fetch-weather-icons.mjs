/**
 * Generates lib/weather/weather-icon-svgs.ts from the Iconify API.
 *
 * We self-host the SVG markup (no runtime icon dependency, and emoji-free sets
 * render reliably on the Pi kiosk, which lacks a color-emoji font). Iconify is
 * just the build-time source — it already normalizes every set to a 1em-sized
 * <svg>, so font-size drives icon size exactly like the emoji it replaces.
 *
 * Run manually after changing the glyph/name maps below:
 *   npm run weather-icons        (alias for: node scripts/fetch-weather-icons.mjs)
 *
 * Sets + licenses (all permissive):
 *   lucide        — ISC          (monochrome line-art, currentColor)
 *   meteocons     — MIT, B.Milius (full color, static)
 *   weather-icons — SIL OFL 1.1   (Erik Flowers; monochrome, currentColor)
 */

import { writeFile } from 'node:fs/promises';

// Iconify collection prefix per config set key.
const PREFIX = { lucide: 'lucide', meteocons: 'meteocons', 'weather-icons': 'wi' };

// glyph -> icon name, per set. Glyphs are the semantic buckets WMO codes map to
// (see lib/weather/wmo.ts). Several WMO codes share a glyph, mirroring the old
// emoji map.
const SETS = {
  lucide: {
    'clear-day': 'sun',
    'clear-night': 'moon',
    'partly-day': 'cloud-sun',
    'partly-night': 'cloud-moon',
    cloudy: 'cloud',
    fog: 'cloud-fog',
    drizzle: 'cloud-drizzle',
    rain: 'cloud-rain',
    sleet: 'cloud-hail',
    snow: 'cloud-snow',
    thunder: 'cloud-lightning',
    unknown: 'cloud-off',
  },
  meteocons: {
    'clear-day': 'clear-day',
    'clear-night': 'clear-night',
    'partly-day': 'partly-cloudy-day',
    'partly-night': 'partly-cloudy-night',
    cloudy: 'overcast',
    fog: 'fog',
    drizzle: 'drizzle',
    rain: 'rain',
    sleet: 'sleet',
    snow: 'snow',
    thunder: 'thunderstorms',
    unknown: 'not-available',
  },
  'weather-icons': {
    'clear-day': 'day-sunny',
    'clear-night': 'night-clear',
    'partly-day': 'day-cloudy',
    'partly-night': 'night-alt-cloudy',
    cloudy: 'cloudy',
    fog: 'fog',
    drizzle: 'sprinkle',
    rain: 'rain',
    sleet: 'sleet',
    snow: 'snow',
    thunder: 'thunderstorm',
    unknown: 'na',
  },
};

// Iconify hands out random internal ids (gradients/symbols). The same icon can
// appear several times on the dashboard (current + forecast days), so rename
// ids to a per-(set,glyph) namespace — unique across glyphs, identical across
// repeats of one glyph, which keeps url(#id) references valid.
function namespaceIds(svg, prefix) {
  const idMap = new Map();
  let n = 0;
  svg = svg.replace(/id="(SVG[0-9A-Za-z]+)"/g, (_, id) => {
    if (!idMap.has(id)) idMap.set(id, `${prefix}-${n++}`);
    return `id="${idMap.get(id)}"`;
  });
  svg = svg.replace(/#(SVG[0-9A-Za-z]+)/g, (m, id) => (idMap.has(id) ? `#${idMap.get(id)}` : m));
  return svg;
}

async function fetchIcon(set, name) {
  const url = `https://api.iconify.design/${PREFIX[set]}/${name}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
  const svg = (await res.text()).trim();
  if (!svg.startsWith('<svg')) throw new Error(`${url} → not an SVG: ${svg.slice(0, 60)}`);
  return svg;
}

const out = {};
let failures = 0;
for (const [set, glyphs] of Object.entries(SETS)) {
  out[set] = {};
  for (const [glyph, name] of Object.entries(glyphs)) {
    try {
      const svg = namespaceIds(await fetchIcon(set, name), `${set}-${glyph}`);
      out[set][glyph] = svg;
      console.log(`ok   ${set}/${glyph} (${name})`);
    } catch (err) {
      failures++;
      console.error(`FAIL ${set}/${glyph} (${name}): ${err.message}`);
    }
  }
}

if (failures) {
  console.error(`\n${failures} icon(s) failed — fix the name map and re-run.`);
  process.exit(1);
}

const banner = `// AUTO-GENERATED by scripts/fetch-weather-icons.mjs — do not edit by hand.
// Self-hosted weather-icon SVGs (sized to 1em). Regenerate to add/swap sets.
`;
const body = `import type { WeatherGlyph } from './wmo';

export type SvgIconSet = 'lucide' | 'meteocons' | 'weather-icons';

export const WEATHER_ICON_SVGS: Record<SvgIconSet, Record<WeatherGlyph, string>> =
${JSON.stringify(out, null, 2)} as const;
`;

await writeFile('lib/weather/weather-icon-svgs.ts', banner + '\n' + body);
console.log('\nWrote lib/weather/weather-icon-svgs.ts');
