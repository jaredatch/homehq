#!/usr/bin/env node
/**
 * Regenerates the self-hosted colour emoji font (public/fonts/emoji/) and the
 * @font-face block in styles/fonts.css.
 *
 * WHY: the kitchen Pi ships no font containing emoji codepoints, so titles like
 * "🚖 Eleanor" render as tofu boxes on the wall. We self-host rather than rely
 * on the OS — see CLAUDE.md → "Emoji in event titles".
 *
 * Google Fonts serves Noto Color Emoji as COLRv1 (real vector colour) split
 * into ~10 subset slices, each with its own unicode-range. Vendoring all of
 * them costs ~2 MB in the repo but the browser only ever fetches the slice a
 * glyph actually needs — the transport slice holding 🚖 is ~115 KB.
 *
 * Run: npm run emoji-font
 */
import { mkdir, writeFile, rm } from 'node:fs/promises';
import * as prettier from 'prettier';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'public/fonts/emoji');
const CSS_OUT = resolve(ROOT, 'styles/fonts.css');
const FAMILY = 'HomeHQ Emoji';

// A modern desktop UA is what makes Google Fonts hand back woff2 + COLRv1.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const SRC = 'https://fonts.googleapis.com/css2?family=Noto+Color+Emoji&display=swap';

const css = await (await fetch(SRC, { headers: { 'User-Agent': UA } })).text();

const faces = [...css.matchAll(/@font-face\s*{([^}]+)}/g)].map((m) => ({
  url: m[1].match(/src:\s*url\(([^)]+)\)/)[1],
  range: m[1].match(/unicode-range:\s*([^;]+);/)[1].trim(),
}));
if (!faces.length) throw new Error('no @font-face blocks parsed — did Google change the response?');

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

// OFL 1.1 requires the licence to travel with the font — and this directory is
// wiped on every run, so fetch it back rather than leaving it to survive.
const LICENSE_URL = 'https://raw.githubusercontent.com/googlefonts/noto-emoji/main/fonts/LICENSE';
const licence = await (await fetch(LICENSE_URL)).text();
if (!/SIL Open Font License/i.test(licence)) throw new Error('licence fetch looks wrong');
await writeFile(resolve(OUT_DIR, 'LICENSE.txt'), licence);

let total = 0;
const blocks = [];
for (const [i, face] of faces.entries()) {
  const bytes = Buffer.from(await (await fetch(face.url)).arrayBuffer());
  const name = `noto-color-emoji.${i}.woff2`;
  await writeFile(resolve(OUT_DIR, name), bytes);
  total += bytes.length;
  console.log(`  slice ${i}: ${(bytes.length / 1024).toFixed(0)} KB`);
  blocks.push(
    [
      '@font-face {',
      `\tfont-family: '${FAMILY}';`,
      `\tsrc: url('/fonts/emoji/${name}') format('woff2');`,
      '\tfont-style: normal;',
      '\tfont-weight: 400;',
      '\tfont-display: swap;',
      `\tunicode-range: ${face.range};`,
      '}',
    ].join('\n')
  );
}

const header = `/* ============================================================================
   Fonts — self-hosted colour emoji.

   GENERATED BY scripts/fetch-emoji-font.mjs (npm run emoji-font). Do not edit
   by hand; re-run the script instead.

   WHY THIS EXISTS: event titles are open text the family types, and they use
   emoji ("🚖 Eleanor" for a school pickup). The kitchen Pi (Raspberry Pi OS /
   Debian trixie) ships NO font containing emoji codepoints, so Chromium drew
   every one as a tofu box — "[]" on the wall while the same page looked right
   on a Mac. Nothing is wrong with the data: same droplet, same bundle, only the
   client differs.

   The weather icons solved the same Pi limitation with inline SVGs, but that
   only works because weather glyphs are a CLOSED set the app itself chooses.
   Event titles are an OPEN set, so they need a font.

   Noto Color Emoji, COLRv1 (real vector colour), as Google Fonts slices it:
   ~${(total / 1024 / 1024).toFixed(1)} MB vendored across ${faces.length} subsets, but each carries its own
   unicode-range so the browser fetches ONLY the slice a glyph needs — the
   transport subset holding 🚖 is ~115 KB, and an emoji-free page costs nothing.
   A monochrome build was tried first and rejected: at event-chip size the
   line-art taxi collapsed into an illegible smudge.

   The family name is deliberately '${FAMILY}', not 'Noto Color Emoji', so a
   copy installed on the host OS can never silently shadow the vendored one.
   It sits AFTER Inter in the body stack (styles/base.css), so it can only ever
   supply glyphs Inter lacks.
   ============================================================================ */

`;

// Format with the repo's own Prettier config (CSS is tab-indented here), so a
// regenerated file never trips `npm run format:check`.
const out = header + blocks.join('\n\n') + '\n';
await writeFile(
  CSS_OUT,
  await prettier.format(out, { ...(await prettier.resolveConfig(CSS_OUT)), parser: 'css' })
);
console.log(
  `\n${faces.length} slices, ${(total / 1024 / 1024).toFixed(2)} MB → public/fonts/emoji/`
);
console.log(`wrote ${CSS_OUT}`);
